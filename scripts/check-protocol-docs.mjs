import { readdir, readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = dirname(scriptDirectory)
const protocolRoot = join(repositoryRoot, 'protocol')
const docsProtocolRoot = join(repositoryRoot, 'docs', 'protocol')

const expectedSpecifications = [
  '00-overview.md',
  '01-wire-format.md',
  '02-control-plane.md',
  '03-identity.md',
  '04-network-model.md',
  '05-discovery.md',
  '06-broadcast.md',
  '07-transport.md',
  '08-security.md',
  '09-versioning.md',
  '10-errata.md'
]

const generatedNotice = [
  '<!-- Generated by scripts/sync-protocol-docs.mjs. Do not edit. -->',
  '',
  '',
].join('\n')

function fail(message) {
  process.stderr.write(`protocol documentation check failed: ${message}\n`)
  process.exitCode = 1
}

async function markdownFiles(directory) {
  return (await readdir(directory))
    .filter((name) => name.endsWith('.md'))
    .sort()
}

async function compareFile(source, generated) {
  const [sourceBytes, generatedBytes] = await Promise.all([
    readFile(source),
    readFile(generated)
  ])

  if (!sourceBytes.equals(generatedBytes)) {
    fail(`${generated} is not synchronized with ${source}`)
  }
}

const actualSpecifications = await markdownFiles(join(protocolRoot, 'spec'))
if (JSON.stringify(actualSpecifications) !== JSON.stringify(expectedSpecifications)) {
  fail(
    `expected specifications ${expectedSpecifications.join(', ')}, found ${actualSpecifications.join(', ')}`
  )
}

const generatedSpecifications = await markdownFiles(
  join(docsProtocolRoot, 'spec')
)
if (JSON.stringify(generatedSpecifications) !== JSON.stringify(expectedSpecifications)) {
  fail('rendered specification set does not match the normative set')
}

for (const name of expectedSpecifications) {
  await compareFile(
    join(protocolRoot, 'spec', name),
    join(docsProtocolRoot, 'spec', name)
  )
}

const sourceAdrs = (await markdownFiles(join(protocolRoot, 'adr'))).filter(
  (name) => name !== 'README.md'
)
const generatedAdrs = (await markdownFiles(join(docsProtocolRoot, 'adr'))).filter(
  (name) => name !== 'index.md'
)

if (JSON.stringify(sourceAdrs) !== JSON.stringify(generatedAdrs)) {
  fail('rendered ADR set does not match the normative set')
}

for (const name of sourceAdrs) {
  await compareFile(
    join(protocolRoot, 'adr', name),
    join(docsProtocolRoot, 'adr', name)
  )
}

const [protocolReadme, renderedIndex, adrReadme, renderedAdrIndex] =
  await Promise.all([
    readFile(join(protocolRoot, 'README.md'), 'utf8'),
    readFile(join(docsProtocolRoot, 'index.md'), 'utf8'),
    readFile(join(protocolRoot, 'adr', 'README.md'), 'utf8'),
    readFile(join(docsProtocolRoot, 'adr', 'index.md'), 'utf8')
  ])

if (renderedIndex !== `${generatedNotice}${protocolReadme}`) {
  fail('rendered protocol index is not synchronized')
}

if (renderedAdrIndex !== `${generatedNotice}${adrReadme}`) {
  fail('rendered ADR index is not synchronized')
}

const placeholderPattern = /\b(?:TODO|TBD|FIXME)\b|open phase 1 decisions|remain open phase 1/iu
for (const name of expectedSpecifications) {
  const contents = await readFile(join(protocolRoot, 'spec', name), 'utf8')
  if (placeholderPattern.test(contents)) {
    fail(`${name} contains an unresolved specification placeholder`)
  }

  const references = contents.matchAll(/`([0-9]{2}-[a-z0-9-]+\.md)`/gu)
  for (const reference of references) {
    if (!expectedSpecifications.includes(reference[1])) {
      fail(`${name} references missing specification ${reference[1]}`)
    }
  }
}

if (process.exitCode === undefined) {
  process.stdout.write('protocol documentation check passed\n')
}
