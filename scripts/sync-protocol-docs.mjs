import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = dirname(scriptDirectory)
const protocolRoot = join(repositoryRoot, 'protocol')
const outputRoot = join(repositoryRoot, 'docs', 'protocol')

await rm(outputRoot, { recursive: true, force: true })
await mkdir(outputRoot, { recursive: true })

await cp(join(protocolRoot, 'spec'), join(outputRoot, 'spec'), {
  recursive: true
})
await cp(join(protocolRoot, 'adr'), join(outputRoot, 'adr'), {
  recursive: true
})

const protocolReadme = await readFile(join(protocolRoot, 'README.md'), 'utf8')
const adrReadme = await readFile(join(protocolRoot, 'adr', 'README.md'), 'utf8')
const generatedNotice = [
  '<!-- Generated by scripts/sync-protocol-docs.mjs. Do not edit. -->',
  '',
  '',
].join('\n')

await writeFile(
  join(outputRoot, 'index.md'),
  `${generatedNotice}${protocolReadme}`,
  'utf8'
)
await writeFile(
  join(outputRoot, 'adr', 'index.md'),
  `${generatedNotice}${adrReadme}`,
  'utf8'
)
await rm(join(outputRoot, 'adr', 'README.md'))
